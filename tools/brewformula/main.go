// Command brewformula renders the Homebrew formula for a release from the
// checksums.txt GoReleaser publishes, so Formula/create-bootable-usb.rb
// always points at the latest release archives:
//
//	go run ./tools/brewformula -version 0.0.2 -checksums dist/checksums.txt -o Formula/create-bootable-usb.rb
//
// The release workflow runs it after every release.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"
	"text/template"
)

const repo = "https://github.com/elvisgastelum/create-bootable-usb"

// archives are the release files the formula installs, by platform.
var archives = map[string]string{
	"MacARM":     "create-bootable-usb_macos_arm64.tar.gz",
	"MacIntel":   "create-bootable-usb_macos_x86_64.tar.gz",
	"LinuxARM":   "create-bootable-usb_linux_arm64.tar.gz",
	"LinuxIntel": "create-bootable-usb_linux_x86_64.tar.gz",
}

var (
	versionRE = regexp.MustCompile(`^\d+\.\d+\.\d+$`)
	sha256RE  = regexp.MustCompile(`^[0-9a-f]{64}$`)
)

var formula = template.Must(template.New("formula").Parse(`# Generated by tools/brewformula for each release; edit the template there.
class CreateBootableUsb < Formula
  desc "Write ISO and IMG images to USB devices from a terminal UI"
  homepage "{{.Repo}}"
  license "MIT"

  livecheck do
    url :homepage
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "{{.Base}}/{{.MacARM.File}}"
      sha256 "{{.MacARM.SHA}}"
    end
    on_intel do
      url "{{.Base}}/{{.MacIntel.File}}"
      sha256 "{{.MacIntel.SHA}}"
    end
  end

  on_linux do
    on_arm do
      url "{{.Base}}/{{.LinuxARM.File}}"
      sha256 "{{.LinuxARM.SHA}}"
    end
    on_intel do
      url "{{.Base}}/{{.LinuxIntel.File}}"
      sha256 "{{.LinuxIntel.SHA}}"
    end
  end

  def install
    bin.install "create-bootable-usb"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/create-bootable-usb --version")
  end
end
`))

type archive struct{ File, SHA string }

func main() {
	version := flag.String("version", "", "release version, e.g. 0.0.2 (a leading v is ignored)")
	sums := flag.String("checksums", "dist/checksums.txt", "the release's checksums.txt")
	out := flag.String("o", "", "write the formula to this file instead of standard output")
	flag.Parse()

	data, err := os.ReadFile(*sums)
	if err != nil {
		fail(err)
	}
	text, err := render(*version, data)
	if err != nil {
		fail(err)
	}
	if *out == "" {
		fmt.Print(text)
		return
	}
	if err := os.WriteFile(*out, []byte(text), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "brewformula:", err)
	os.Exit(1)
}

// render builds the formula for version from a checksums.txt document
// ("<sha256>  <file>" per line).
func render(version string, checksums []byte) (string, error) {
	version = strings.TrimPrefix(version, "v")
	if !versionRE.MatchString(version) {
		return "", fmt.Errorf("version %q is not MAJOR.MINOR.PATCH", version)
	}
	sums := map[string]string{}
	scanner := bufio.NewScanner(bytes.NewReader(checksums))
	for scanner.Scan() {
		if fields := strings.Fields(scanner.Text()); len(fields) == 2 {
			sums[fields[1]] = fields[0]
		}
	}

	data := map[string]any{
		"Repo":    repo,
		"Version": version,
		"Base":    repo + "/releases/download/v" + version,
	}
	for key, file := range archives {
		sum, ok := sums[file]
		if !ok {
			return "", fmt.Errorf("the checksums file has no entry for %s", file)
		}
		if !sha256RE.MatchString(sum) {
			return "", fmt.Errorf("%s has an invalid sha256 %q", file, sum)
		}
		data[key] = archive{File: file, SHA: sum}
	}

	var buf bytes.Buffer
	if err := formula.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}
